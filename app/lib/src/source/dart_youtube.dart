/// yt-dlp가 없는 곳(Android)의 YouTube.
///
/// - 목록(채널 최신·재생목록·검색): InnerTube 직접 ([InnertubeBrowser]).
///   youtube_explode_dart 3.1.0의 목록 파싱은 지금 YouTube 화면 형식에서 제목·길이가 비어 온다.
/// - 영상·소리 주소, 자막 트랙: youtube_explode_dart.
/// - 자막 내용: 트랙 주소(srv1 XML)를 받아 WebVTT로 바꾼다.
class DartYoutube implements YoutubeBackend {
  DartYoutube({yte.YoutubeExplode? explode})
    : _yt = explode ?? yte.YoutubeExplode();

  final yte.YoutubeExplode _yt;
  final _channelIds = <String, String>{};

  late final _browser = InnertubeBrowser(
    channelId: (handle) async => _channelIds[handle] ??=
        (await _yt.channels.getByHandle('@$handle')).id.value,
  );

  @override
  Future<Map<String, dynamic>> listPlaylist(
    String url, {
    required int start,
    required int end,
  }) => _browser.listPlaylist(url, start: start, end: end);

  @override
  Future<YoutubeMedia> resolve(String url) async {
    final id = parseYoutubeId(url);
    if (id == null) throw YtDlpException('YouTube 링크가 아닙니다: $url');
    final (video, manifest, captions) = await (
      _yt.videos.get(id),
      _yt.videos.streams.getManifest(id),
      _yt.videos.closedCaptions.getManifest(id),
    ).wait;
    final (v, a) = pickStreams(manifest);
    final tracks = [
      for (final t in captions.tracks)
        CaptionTrack(
          lang: t.language.code,
          url: t.url.toString(),
          auto: t.isAutoGenerated,
        ),
    ];
    final (original, korean, language) = pickCaptions(tracks);
    return YoutubeMedia(
      id: id,
      title: video.title,
      videoUrl: v.url.toString(),
      audioUrl: a?.url.toString(),
      language: language,
      original: original,
      korean: korean,
      duration: video.duration,
    );
  }

  @override
  Future<String> fetchCaption(YoutubeMedia media, CaptionTrack track) async {
    final client = HttpClient();
    try {
      final req = await client.getUrl(Uri.parse(track.url));
      final res = await req.close();
      final body = await res.transform(utf8.decoder).join();
      // 요청이 많으면 YouTube가 사람 확인 페이지(HTML)를 돌려준다
      if (res.statusCode != 200 || !body.contains('<transcript')) {
        throw YtDlpException('자막(${track.lang})을 받지 못했습니다 (${res.statusCode})');
      }
      return transcriptToVtt(body);
    } finally {
      client.close();
    }
  }
}

/// 재생할 스트림: 영상만 있는 mp4(1080p 이하, H.264 우선) + 소리만 있는 mp4.
/// 없으면 영상·소리가 합쳐진 스트림. (영상, 소리 또는 null)
(yte.StreamInfo, yte.StreamInfo?) pickStreams(
  yte.StreamManifest m, {
  int maxHeight = 1080,
}) {
  final videos =
      m.videoOnly
          .where(
            (s) =>
                s.container == yte.StreamContainer.mp4 &&
                s.videoResolution.height <= maxHeight,
          )
          .toList()
        ..sort((a, b) {
          final c = a.videoResolution.height.compareTo(
            b.videoResolution.height,
          );
          if (c != 0) return c;
          // 같은 화질이면 H.264(avc1) — 하드웨어 디코딩이 되는 기기가 많다
          final av = a.videoCodec.startsWith('avc1') ? 1 : 0;
          final bv = b.videoCodec.startsWith('avc1') ? 1 : 0;
          return av.compareTo(bv);
        });
  final audios =
      m.audioOnly.where((s) => s.container == yte.StreamContainer.mp4).toList()
        ..sort((a, b) => a.bitrate.compareTo(b.bitrate));
  final muxed = m.muxed.toList()
    ..sort(
      (a, b) => a.videoResolution.height.compareTo(b.videoResolution.height),
    );
  if (videos.isNotEmpty && audios.isNotEmpty) {
    return (videos.last, audios.last);
  }
  if (muxed.isNotEmpty) return (muxed.last, null);
  throw const FormatException('재생 가능한 스트림이 없습니다');
}

/// 자막 고르기 (데스크톱 [YoutubeMedia.fromInfoJson]과 같은 순서).
/// 원어: 사람이 단 영어 → 자동 자막(음성 언어) → 사람이 단 첫 자막.
/// 한국어: 사람이 단 것만 (YouTube 자동 번역은 요청이 막히는 일이 많아 Claude 번역으로 넘긴다).
/// (원어, 한국어, 영상 언어)
(CaptionTrack?, CaptionTrack?, String?) pickCaptions(
  List<CaptionTrack> tracks,
) {
  bool isLang(String code, String lang) =>
      code == lang || code.startsWith('$lang-');
  final manual = tracks.where((t) => !t.auto).toList();
  final auto = tracks.where((t) => t.auto).firstOrNull;
  // 자동 자막은 음성을 받아 적은 것이라 그 언어가 영상 언어다
  final language = auto?.lang.split('-').first;
  final orig = language ?? 'en';
  final original =
      manual.where((t) => isLang(t.lang, orig)).firstOrNull ??
      auto ??
      manual.firstOrNull;
  final korean = orig == 'ko'
      ? null
      : manual.where((t) => isLang(t.lang, 'ko')).firstOrNull;
  return (original, korean, language);
}

/// YouTube 자막 XML(srv1: `<transcript><text start dur>…`) → WebVTT
String transcriptToVtt(String xml) {
  String two(int n) => n.toString().padLeft(2, '0');
  String ts(double sec) {
    final ms = (sec * 1000).round();
    final h = ms ~/ 3600000, m = ms ~/ 60000 % 60, s = ms ~/ 1000 % 60;
    return '${two(h)}:${two(m)}:${two(s)}.${(ms % 1000).toString().padLeft(3, '0')}';
  }

  final out = StringBuffer('WEBVTT\n\n');
  final re = RegExp(
    r'<text start="([\d.]+)"(?: dur="([\d.]+)")?[^>]*>(.*?)</text>',
    dotAll: true,
  );
  for (final m in re.allMatches(xml)) {
    final start = double.parse(m[1]!);
    final dur = double.tryParse(m[2] ?? '') ?? 2;
    // 엔티티가 두 번 감싸여 온다 (&amp;#39; → &#39; → ')
    final text = _unescape(_unescape(m[3]!)).replaceAll(RegExp(r'<[^>]+>'), '');
    if (text.trim().isEmpty) continue;
    out
      ..writeln('${ts(start)} --> ${ts(start + dur)}')
      ..writeln(text.trim())
      ..writeln();
  }
  return out.toString();
}

String _unescape(String s) => s
    .replaceAllMapped(
      RegExp(r'&#(\d+);'),
      (m) => String.fromCharCode(int.parse(m[1]!)),
    )
    .replaceAllMapped(
      RegExp(r'&#x([0-9a-fA-F]+);'),
      (m) => String.fromCharCode(int.parse(m[1]!, radix: 16)),
    )
    .replaceAll('&quot;', '"')
    .replaceAll('&lt;', '<')
    .replaceAll('&gt;', '>')
    .replaceAll('&amp;', '&');
